async function main() {
  console.log("=== Customer Seed from AR Data ===\n");

  // Parse raw data
  const lines = RAW_DATA.split("\n").filter((l) => l.trim());
  const records: Array<{ date: string; name: string; receipt: string; amount: number }> = [];

  for (const line of lines) {
    const parts = line.split("\t");
    if (parts.length < 4) continue;
    const [dateStr, name, receipt, amountStr] = parts;
    records.push({
      date: dateStr.trim(),
      name: name.trim(),
      receipt: receipt.trim(),
      amount: parseFloat(amountStr.trim()) || 0,
    });
  }
  console.log(`Parsed ${records.length} raw records`);

  // Filter out TALYER entries
  const talyerCount = records.filter((r) => r.name.toUpperCase().startsWith("TALYER")).length;
  const customerRecords = records.filter((r) => !r.name.toUpperCase().startsWith("TALYER"));
  console.log(`Skipped ${talyerCount} TALYER (internal) entries`);

  // Aggregate by customer name
  const customerMap = new Map<string, { name: string; total: number; count: number; receipts: Set<string> }>();
  for (const r of customerRecords) {
    let normName = r.name.trim();
    normName = NAME_ALIASES[normName] ?? normName;
    const key = normName.toUpperCase();

    if (!customerMap.has(key)) {
      customerMap.set(key, { name: normName, total: 0, count: 0, receipts: new Set() });
    }
    const entry = customerMap.get(key)!;
    entry.total += r.amount;
    entry.count++;
    entry.receipts.add(r.receipt);
  }
  console.log(`Found ${customerMap.size} unique customer names\n`);

  // Check existing customers
  const existing = await db
    .select({ name: customers.name })
    .from(customers)
    .where(eq(customers.orgId, ORG_ID));
  const existingNames = new Set(existing.map((c) => c.name.toUpperCase()));

  let created = 0;
  let skipped = 0;
  let counter = existing.length;

  for (const [key, data] of customerMap) {
    // Check if already exists (case-insensitive)
    if (existingNames.has(key)) {
      skipped++;
      continue;
    }

    // Also check title-cased version
    const displayName = toTitleCase(data.name);
    if (existingNames.has(displayName.toUpperCase())) {
      skipped++;
      continue;
    }

    const type = classifyCustomer(data.name);
    counter++;
    const phone = `AR-${String(counter).padStart(4, "0")}`;

    // Map GOVERNMENT to valid enum (stored as FLEET in the DB since there's no GOVERNMENT enum)
    const dbType = type === "GOVERNMENT" ? "FLEET" : type === "SHOP" ? "SHOP" : "INDIVIDUAL";

    try {
      await db.insert(customers).values({
        orgId: ORG_ID,
        name: displayName,
        phone,
        customerType: dbType,
        creditLimit: "0",
        paymentTermsDays: 30,
        currentBalance: "0",
        totalPurchases: String(Math.round(data.total * 100) / 100),
        isActive: true,
        notes: type === "GOVERNMENT"
          ? `Government account. ${data.receipts.size} receipts (Q-series). Total AR: ₱${data.total.toLocaleString("en-PH", { minimumFractionDigits: 2 })}`
          : `Imported from AR data. ${data.receipts.size} receipts (Q-series).`,
      });
      created++;
      existingNames.add(displayName.toUpperCase());
    } catch (err: any) {
      if (err.code === "23505") {
        // Duplicate phone
        skipped++;
      } else {
        console.error(`  ERROR inserting ${displayName}: ${err.message}`);
      }
    }
  }

  console.log(`\n=== Summary ===`);
  console.log(`  Created: ${created} customers`);
  console.log(`  Skipped: ${skipped} (already existed or duplicate)`);
  console.log(`  TALYER entries skipped: ${talyerCount}`);
  console.log(`  Total in database: ${existing.length + created}`);

  process.exit(0);
}

main().catch((err) => {
  console.error("Fatal error:", err);
  process.exit(1);
});
