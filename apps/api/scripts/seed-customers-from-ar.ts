// Name normalization — BMEX and BMEX - NAGA are the same
const NAME_ALIASES: Record<string, string> = {
  "BMEX - NAGA": "BMEX",
};

function classifyCustomer(name: string): "INDIVIDUAL" | "SHOP" | "GOVERNMENT" {
  const upper = name.toUpperCase();

  if (GOVERNMENT_KEYWORDS.some((kw) => upper.includes(kw))) return "GOVERNMENT";
  if (SHOP_EXACT.has(name)) return "SHOP";
  if (SHOP_KEYWORDS.some((kw) => upper.includes(kw))) return "SHOP";

  // "LASTNAME, FIRSTNAME" pattern → individual
  if (name.includes(",")) return "INDIVIDUAL";

  // Multi-word names with / → special customer, treat as SHOP
  if (name.includes("/")) return "SHOP";

  return "SHOP"; // default
}

function toTitleCase(s: string): string {
  return s
    .toLowerCase()
    .replace(/(^|\s|[-/])(\w)/g, (_, pre, c) => pre + c.toUpperCase())
    .replace(/\b(Inc|Corp|Llc|Ltd)\b/gi, (m) => m.toUpperCase())
    .replace(/\bDy\b/, "Dy")
    .replace(/\bLgu\b/, "LGU")
    .replace(/\bDeped\b/, "DepEd")
    .replace(/\bDti\b/, "DTI")
    .replace(/\bHvac\b/, "HVAC")
    .replace(/\bRmn\b/, "RMN")
    .replace(/\bCbs\b/, "CBS")
    .replace(/\bBmex\b/, "BMEX")
    .replace(/\bNvs\b/, "NVS")
    .replace(/\bGn\b/, "GN")
    .replace(/\bRt\b/, "RT")
    .replace(/\bJt\b/, "JT")
    .replace(/\bAtty\b/, "Atty.")
    .replace(/\bAet\b/, "AET")
    .replace(/\bVgdc\b/, "VGDC");
}

